"""Generate the Remotion REAL3D comp for a daily Short (adapted from the factory gen_comp.py).
usage: python3 daily/gen_comp.py <work dir> <case dir with cues.json + vo.json>   -> rm/src/real3d/<slug>/{Comp.jsx, entry.jsx, palette.pick.js, vo.json}
Plates must be at rm/public/real3d/<slug>/sNN.mp4. Prints COMP=<id> FRAMES=<n>."""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, load_plan, comp_id
work, case = sys.argv[1:3]
p = load_plan(work)
R = ROOT
slug = p['slug']
cfg = {'slug': slug, 'comp': comp_id(slug), 'scheme': p['scheme'], 'seed': sum(map(ord, slug)) % 9000 + 1000,
       'shots': [dict(name=f's{k+1:02d}', src=f's{k+1:02d}.mp4', head=s.get('head'), chip=s.get('chip'), chip_w=max(420, min(760, 26 * len(s.get('chip') or '') + 120)))
                 for k, s in enumerate(p['shots'])]}
if p.get('credit'): cfg['credit'] = {'text': p['credit'][:60], 'shot': 0, 'y': 1100}
C = case
cues = json.load(open(C + '/cues.json')); vo = json.load(open(C + '/vo.json')); W = vo['words']
FR = cues['frames']; cuts = cues['cuts']
def t(word, after=0):
    q = word.strip("'.,:?").lower()
    for w in W:
        if w[1] >= after and w[0].strip("'.,:?").lower().startswith(q): return w[1]
    raise SystemExit('word ' + word)
import re
for s_ in cfg['shots']:
    if s_.get('startFrom') == 'FROM_CUES':
        m = re.search(r'startFrom (\d+)', cues['plates'][s_['name']][2]); s_['startFrom'] = int(m.group(1))
shots = cfg['shots']; assert len(shots) == len(cuts), (len(shots), len(cuts))
fr = [round(c * 30) for c in cuts] + [FR]
P = 'real3d/%s/' % slug
pl = []; heads = []; chips = []
for i, s in enumerate(shots):
    f0, f1 = fr[i], fr[i + 1]; d = f1 - f0
    for seg in s.get('segs', [{'src': s['src'], 'startFrom': s.get('startFrom', 0), 'frac': 1.0}]):
        pass
    segs = s.get('segs')
    if segs:
        a = f0
        for k, g in enumerate(segs):
            b = f1 if k == len(segs) - 1 else a + g['n']
            pl.append({'src': P + g['src'], 'from': a, 'dur': b - a, 'startFrom': g.get('startFrom', 0), 'drift': 0.01})
            a = b
    else:
        pl.append({'src': P + s['src'], 'from': f0, 'dur': d, 'startFrom': s.get('startFrom', 0), 'drift': 0.01})
    if s.get('head'): heads.append((f0 + 4, d - 8, s['head']))
    if s.get('chip'): chips.append((f0 + 8, d - 10, s['chip'], s.get('chip_w', 640)))
ph = cfg.get('photo')
if ph: pf0 = round((t(ph['word'], ph.get('after', 0)) - 0.15) * 30); pf1 = round((t(ph['end_word'], ph.get('end_after', 0)) - 0.07) * 30)
else: pf0 = pf1 = 0
scheme = cfg['scheme']; comp = cfg['comp']
J = []
J.append(f"// {slug}: REAL3D Short, {FR / 30:.2f} s = {FR} f. Generated by daily/gen_comp.py from cues.json (do not hand-edit timings).")
J.append(f"// Real artifact: {(ph or cfg.get('credit', {})).get('tag', (ph or cfg.get('credit', {})).get('text',''))}, evidence card f{pf0}-{pf1}. Plates = Blender Cycles on GitHub, public/{P}.")
J.append("import {AbsoluteFill, Sequence, Img, staticFile, useCurrentFrame, interpolate, Easing} from 'remotion';")
J.append("import {PlateTrack, Real3DFinish, R3DTag, IAMark, R3DFonts, R3DCaption, R3DHead, R3DLabel, SCHEMES} from '../Real3DKit.jsx';")
J.append("import VO from './vo.json';")
J.append(f"export const FRAMES = {FR};")
J.append(f"export const SCHEME = '{scheme}';")
J.append("const ez = Easing.bezier(0.33, 0, 0.2, 1); const cl = {extrapolateLeft: 'clamp', extrapolateRight: 'clamp'};")
J.append("const S = SCHEMES[SCHEME];")
J.append("const plates = " + json.dumps(pl) + ";")
J.append("""const Scrim = ({inF, outF, h = 640}) => { const f = useCurrentFrame(); const o = Math.min(1, Math.max(0, (f - inF) / 6)) * (1 - Math.min(1, Math.max(0, (f - outF) / 8)));
  return <div style={{position: 'absolute', top: 0, left: 0, width: 1080, height: h, opacity: o, background: 'linear-gradient(rgba(0,0,0,0.66) 0%, rgba(0,0,0,0.44) 45%, rgba(0,0,0,0) 100%)'}} />; };
const Head = ({from, dur, lines}) => (<Sequence from={from} durationInFrames={dur}><Scrim inF={0} outF={dur - 8} /><R3DHead scheme={SCHEME} lines={lines} inF={0} outF={dur - 6} /></Sequence>);
const Bottom = () => <div style={{position: 'absolute', left: 0, top: 1180, width: 1080, height: 740, background: 'linear-gradient(rgba(0,0,0,0) 0%, rgba(0,0,0,0.5) 40%, rgba(0,0,0,0.62) 100%)'}} />;
const ChipIn = ({text, y, w, dur}) => { const f = useCurrentFrame();
  const t = interpolate(f, [0, 8], [0, 1], {easing: ez, ...cl}) * (1 - interpolate(f, [dur - 8, dur], [0, 1], cl));
  return (<div style={{position: 'absolute', left: (1080 - w) / 2, top: y, width: w, padding: '16px 0', textAlign: 'center', borderRadius: 12, background: S.chip, color: S.chipText, opacity: 0.92 * t, transform: `translateY(${(1 - t) * 14}px)`, fontFamily: 'Montserrat', fontWeight: 800, fontSize: 32, letterSpacing: 2, boxShadow: '0 6px 24px rgba(0,0,0,0.6)', whiteSpace: 'nowrap'}}>{text}</div>); };
const Chip = ({from, dur, text, y = 1100, w = 640}) => (<Sequence from={from} durationInFrames={dur}><ChipIn text={text} y={y} w={w} dur={dur} /></Sequence>);
// Evidence card: the real photo as a lit print, eased scale-in + slow push (no shake).
const Evidence = ({dur, src, y, h}) => { const f = useCurrentFrame();
  const a = interpolate(f, [0, 7], [0, 1], {easing: ez, ...cl}) * (1 - interpolate(f, [dur - 7, dur], [0, 1], cl));
  const s = interpolate(f, [0, dur], [0.94, 1.0], {easing: ez, ...cl});
  return (<AbsoluteFill style={{opacity: a}}>
    <AbsoluteFill style={{background: 'rgba(0,0,0,0.45)'}} />
    <div style={{position: 'absolute', left: 162, top: y, width: 756, height: h, transform: `scale(${s})`, boxShadow: '0 24px 70px rgba(0,0,0,0.85)', border: '10px solid #e9e4d8', background: '#222', overflow: 'hidden'}}>
      <Img src={staticFile(src)} style={{width: '100%', height: '100%', objectFit: 'cover', filter: 'contrast(1.05)'}} />
    </div></AbsoluteFill>); };
const Cap = () => <R3DCaption words={VO.words} scheme={SCHEME} y={1290} backing />;""")
J.append(f"export const {comp} = () => (")
J.append("  <AbsoluteFill style={{background: '#000'}}>")
J.append("    <R3DFonts />")
J.append("    <PlateTrack plates={plates} dip={0} />")
J.append("    <Real3DFinish seed={%d} />" % cfg.get('seed', 1912))
J.append("    <Bottom />")
for (a, d, l) in heads:
    J.append(f"    <Head from={{{a}}} dur={{{d}}} lines={{{json.dumps(l)}}} />")
for (a, d, txt, w) in chips:
    J.append(f"    <Chip from={{{a}}} dur={{{d}}} text={{{json.dumps(txt)}}} w={{{w}}} />")
if ph: J.append(f"    <Sequence from={{{pf0}}} durationInFrames={{{pf1 - pf0}}}><Evidence dur={{{pf1 - pf0}}} src={{'{P}{ph['src']}'}} y={{{ph.get('y', 470)}}} h={{{ph.get('h', 560)}}} /></Sequence>")
if ph: J.append(f"    <Sequence from={{{pf0 + 4}}} durationInFrames={{{pf1 - pf0 - 4}}}><R3DTag text={{{json.dumps(ph['tag'])}}} at={{0}} y={{{cfg.get('tag_y', 1110)}}} size={{28}} /></Sequence>")
cr = cfg.get('credit')
if cr:
    cf0 = fr[cr.get('shot', 0)] + 6; cf1 = fr[cr.get('shot', 0) + 1] - 4
    J.append(f"    <Sequence from={{{cf0}}} durationInFrames={{{cf1 - cf0}}}><R3DTag text={{{json.dumps(cr['text'])}}} at={{0}} y={{{cr.get('y', 1100)}}} size={{26}} /></Sequence>")
J.append("    <Cap />")
J.append(f"    <IAMark y={{{cfg.get('mark_y', 1468)}}} />")
J.append(f"    <R3DLabel y={{{cfg.get('label_y', 1522)}}} />")
J.append("  </AbsoluteFill>\n);")
D = os.path.join(R, 'rm/src/real3d', slug); os.makedirs(D, exist_ok=True)
open(os.path.join(D, comp + '.jsx'), 'w').write('\n'.join(J) + '\n')
open(os.path.join(D, 'palette.pick.js'), 'w').write(f"// HUMANE caption palette for this Short (user 2026-11-03). Logged in R/CAPTION_LOG.csv after the final render.\nimport {{setPalette}} from '../../palette.js';\nsetPalette('{scheme}');\n")
open(os.path.join(D, 'entry.jsx'), 'w').write(f"import './palette.pick.js'; // FIRST import: sets the humane caption palette\nimport {{registerRoot, Composition}} from 'remotion';\nimport {{{comp}, FRAMES}} from './{comp}.jsx';\nregisterRoot(() => <Composition id=\"{comp}\" component={{{comp}}} durationInFrames={{FRAMES}} fps={{30}} width={{1080}} height={{1920}} />);\n")
json.dump({'lines': vo['lines'], 'words': W, 'dur': vo['dur']}, open(os.path.join(D, 'vo.json'), 'w'))
print(f'COMP={comp} FRAMES={FR}'); print('wrote', D, 'frames', FR, 'plates', len(pl), 'heads', len(heads), 'chips', len(chips), 'photo', pf0, pf1)
need = sorted(set(p['src'].split('/')[-1] for p in pl)); print('needs', need)
